class DbOperationsIT {
    private val jdbcUrl = "jdbc:h2:mem:muse;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1"
    private val dbConfig =
        DbConfig(
            name = "h2",
            connection =
                GenericDbConnectionConfig(
                    url = jdbcUrl,
                    driverClassName = "org.h2.Driver",
                    user = "sa",
                    password = "",
                ),
        )
    private val operations = JdbcOperations(DbConnectionFactory(dbConfig, Properties()), TestExpressionEvaluator)

    @BeforeEach
    fun resetSchema() {
        DriverManager.getConnection(jdbcUrl, "sa", "").use { connection ->
            connection.createStatement().use { statement ->
                statement.execute("DROP ALL OBJECTS")
            }
        }
    }

    @Test
    fun `single-row DML query and streaming select execute against a real database`() {
        operations.executeDdl(
            DbExecuteDdlConfig(
                ref(),
                "CREATE TABLE account (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                    "name TEXT NOT NULL, balance INTEGER NOT NULL)",
            ),
            MuseEvent(),
        )
        val insert =
            operations.insert(
                DbInsertConfig(
                    configRef = ref(),
                    sql = "INSERT INTO account(name, balance) VALUES (:name, :balance)",
                    inputParameters = DbParameterSource.Values(mapOf("name" to "Ada", "balance" to 10)),
                    parameterTypes = mapOf("balance" to DbParameterType(JDBCType.INTEGER)),
                    generatedKeys = DbGeneratedKeys(enabled = true, columnNames = listOf("id")),
                ),
                MuseEvent(),
            )
        assertEquals(1, insert.affectedRows)
        assertEquals("1", insert.generatedKeys.getValue("id").toString())

        val update =
            operations.update(
                DbUpdateConfig(
                    ref(),
                    "UPDATE account SET balance = :balance WHERE id = :id",
                    DbParameterSource.Values(mapOf("balance" to 15, "id" to 1L)),
                ),
                MuseEvent(),
            )
        assertEquals(1, update.affectedRows)

        val single =
            operations.querySingle(
                DbQuerySingleConfig(
                    ref(),
                    "SELECT name, balance FROM account WHERE id = :id",
                    DbParameterSource.Values(mapOf("id" to 1L)),
                ),
                MuseEvent(),
            )
        assertEquals("Ada", single["name"])
        assertEquals(15, (single["balance"] as Number).toInt())

        val provider =
            operations.select(
                DbSelectConfig(
                    ref(),
                    "SELECT id, name, balance FROM account ORDER BY id",
                    streamingStrategy =
                        StreamingStrategy.RepeatableInMemory(
                            initialObjectBufferSize = 1,
                            objectBufferSizeIncrement = 1,
                            maxObjectBufferSize = 10,
                        ),
                ),
                MuseEvent(),
            )
        val first = provider.openCursor().use { cursor -> cursor.asSequence().toList() }
        val replay = provider.openCursor().use { cursor -> cursor.asSequence().toList() }
        provider.releaseResources()
        assertEquals(first, replay)
        assertEquals("Ada", first.single()["name"])

        val deleted =
            operations.delete(
                DbDeleteConfig(
                    ref(),
                    "DELETE FROM account WHERE id = :id",
                    DbParameterSource.Values(mapOf("id" to 1L)),
                ),
                MuseEvent(),
            )
        assertEquals(1, deleted)
    }

    @Test
    fun `unsupported select streaming strategy fails before JDBC execution`() {
        assertFailsWith<UnsupportedOperationException> {
            operations.select(
                DbSelectConfig(
                    ref(),
                    "SELECT 1",
                    streamingStrategy = StreamingStrategy.RepeatableFileStore(),
                ),
                MuseEvent(),
            )
        }
    }

    @Test
    fun `bulk DML and script use real batch and local transaction behavior`() {
        val scriptCounts =
            operations.executeScript(
                DbExecuteScriptConfig(
                    configRef = ref(),
                    sql =
                        """
                        CREATE TABLE inventory (id INTEGER PRIMARY KEY, name TEXT NOT NULL, quantity INTEGER NOT NULL);
                        INSERT INTO inventory(id, name, quantity) VALUES (1, 'seed', 1);
                        """.trimIndent(),
                ),
                MuseEvent(),
            )
        assertEquals(2, scriptCounts.size)

        val inserted =
            operations.bulk(
                DbBulkInsertConfig(
                    ref(),
                    "INSERT INTO inventory(id, name, quantity) VALUES (:id, :name, :quantity)",
                    DbBatchParameterSource.Values(
                        listOf(
                            mapOf("id" to 2, "name" to "two", "quantity" to 2),
                            mapOf("id" to 3, "name" to "three", "quantity" to 3),
                        ),
                    ),
                ),
                MuseEvent(),
            )
        assertEquals(listOf(1, 1), inserted)

        val updated =
            operations.bulk(
                DbBulkUpdateConfig(
                    ref(),
                    "UPDATE inventory SET quantity = :quantity WHERE id = :id",
                    DbBatchParameterSource.Values(listOf(mapOf("id" to 2, "quantity" to 20), mapOf("id" to 3, "quantity" to 30))),
                ),
                MuseEvent(),
            )
        assertEquals(listOf(1, 1), updated)

        val deleted =
            operations.bulk(
                DbBulkDeleteConfig(
                    ref(),
                    "DELETE FROM inventory WHERE id = :id",
                    DbBatchParameterSource.Values(listOf(mapOf("id" to 2), mapOf("id" to 3))),
                ),
                MuseEvent(),
            )
        assertEquals(listOf(1, 1), deleted)
    }

    @Test
    fun `script select succeeds and keeps the preceding insert`() {
        val counts =
            operations.executeScript(
                DbExecuteScriptConfig(
                    configRef = ref(),
                    sql = """
                    CREATE TABLE script_rows (id INTEGER PRIMARY KEY, name VARCHAR(20) NOT NULL);
                    INSERT INTO script_rows(id, name) VALUES (1, 'kept');
                    SELECT id, name FROM script_rows;
                """.trimIndent(),
                ),
                MuseEvent(),
            )
        assertEquals(listOf(0, 1), counts)
        val count =
            operations.querySingle(
                DbQuerySingleConfig(ref(), "SELECT COUNT(*) AS count FROM script_rows"),
                MuseEvent(),
            )
        assertEquals(1, (count.getValue("count") as Number).toInt())
    }

    @Test
    fun `failed statement after a script select rolls back the insert`() {
        operations.executeDdl(
            DbExecuteDdlConfig(ref(), "CREATE TABLE script_rollback (id INTEGER PRIMARY KEY, name VARCHAR(20) NOT NULL)"),
            MuseEvent(),
        )
        assertFailsWith<java.sql.SQLException> {
            operations.executeScript(
                DbExecuteScriptConfig(
                    configRef = ref(),
                    sql = """
                    INSERT INTO script_rollback(id, name) VALUES (1, 'kept');
                    SELECT id FROM script_rollback;
                    INSERT INTO script_rollback(id, name) VALUES (1, 'duplicate');
                """.trimIndent(),
                ),
                MuseEvent(),
            )
        }
        val count =
            operations.querySingle(
                DbQuerySingleConfig(ref(), "SELECT COUNT(*) AS count FROM script_rollback"),
                MuseEvent(),
            )
        assertEquals(0, (count.getValue("count") as Number).toInt())
    }

    @Test
    fun `failed bulk operation rolls back every batched row`() {
        operations.executeDdl(
            DbExecuteDdlConfig(ref(), "CREATE TABLE rollback_value (id INTEGER PRIMARY KEY, name TEXT NOT NULL)"),
            MuseEvent(),
        )

        assertFailsWith<java.sql.SQLException> {
            operations.bulk(
                DbBulkInsertConfig(
                    ref(),
                    "INSERT INTO rollback_value(id, name) VALUES (:id, :name)",
                    DbBatchParameterSource.Values(
                        listOf(
                            mapOf("id" to 1, "name" to "first"),
                            mapOf("id" to 1, "name" to "duplicate"),
                        ),
                    ),
                ),
                MuseEvent(),
            )
        }

        val count = operations.querySingle(DbQuerySingleConfig(ref(), "SELECT COUNT(*) AS count FROM rollback_value"), MuseEvent())
        assertEquals(0, (count.getValue("count") as Number).toInt())
    }

    @Test
    fun `stored procedure executes with named input parameters`() {
        val result =
            operations.storedProcedure(
                DbStoredProcedureConfig(
                    configRef = ref(),
                    sql = "CALL ABS(:input)",
                    inputParameters = DbParameterSource.Values(mapOf("input" to -7)),
                    parameterTypes = mapOf("input" to DbParameterType(JDBCType.INTEGER)),
                ),
                MuseEvent(),
            )

        val returnedValue = result.resultSets.single().single().values.single()
        assertEquals(7, (returnedValue as Number).toInt())
    }

    @Test
    fun `row listener emits each database row once with watermark and id`() = runBlocking {
        operations.executeScript(
            DbExecuteScriptConfig(
                configRef = ref(),
                sql =
                    """
                    CREATE TABLE outbox (id BIGINT PRIMARY KEY, body TEXT NOT NULL);
                    INSERT INTO outbox(id, body) VALUES (1, 'first');
                    INSERT INTO outbox(id, body) VALUES (2, 'second');
                    """.trimIndent(),
            ),
            MuseEvent(),
        )
        val source =
            DbRowListenerMuseSource(
                config =
                    DbRowListenerConfig(
                        configRef = ref(),
                        table = "outbox",
                        watermarkColumn = "id",
                        idColumn = "id",
                        settings = DbQuerySettings(maxRows = 10),
                        schedulingStrategy =
                            FixedFrequencyStrategy(
                                frequency = "50",
                                timeUnit = SchedulerTimeUnit.MILLISECONDS,
                            ),
                    ),
                connectionFactory = DbConnectionFactory(dbConfig, Properties()),
                expressionEvaluator = TestExpressionEvaluator,
                properties = Properties(),
            )
        val channel = Channel<MuseEventEnvelope>(Channel.UNLIMITED)
        val sourceJob = launch(Dispatchers.Default) { source.start(channel) }
        try {
            val rows =
                withTimeout(Duration.ofSeconds(5).toMillis()) {
                    List(2) {
                        val envelope = channel.receive()
                        @Suppress("UNCHECKED_CAST")
                        val row = envelope.event.payload?.getOrNull() as Map<String, Any?>
                        envelope.replyTo.complete(envelope.event)
                        row
                    }
                }
            assertEquals(listOf(1L, 2L), rows.map { (it.getValue("id") as Number).toLong() })
            assertNull(withTimeoutOrNull(250) { channel.receive() })
        } finally {
            source.stop()
            sourceJob.cancelAndJoin()
            channel.close()
        }
    }

    @Test
    fun `row listener delivers equal watermarks once across maxRows and a later insert`() = runBlocking {
        operations.executeScript(
            DbExecuteScriptConfig(
                configRef = ref(),
                sql = """
                    CREATE TABLE events (
                        id BIGINT PRIMARY KEY,
                        updated_at TIMESTAMP NOT NULL,
                        body VARCHAR(20) NOT NULL
                    );
                    INSERT INTO events(id, updated_at, body) VALUES
                        (1, TIMESTAMP '2026-01-01 00:00:00', 'first'),
                        (2, TIMESTAMP '2026-01-01 00:00:00', 'second');
                """.trimIndent(),
            ),
            MuseEvent(),
        )
        val source =
            DbRowListenerMuseSource(
                config =
                    DbRowListenerConfig(
                        configRef = ref(),
                        table = "events",
                        watermarkColumn = "updated_at",
                        idColumn = "id",
                        settings = DbQuerySettings(maxRows = 1),
                        schedulingStrategy =
                            FixedFrequencyStrategy(
                                frequency = "50",
                                timeUnit = SchedulerTimeUnit.MILLISECONDS,
                            ),
                    ),
                connectionFactory = DbConnectionFactory(dbConfig, Properties()),
                expressionEvaluator = TestExpressionEvaluator,
                properties = Properties(),
            )
        val channel = Channel<MuseEventEnvelope>(Channel.UNLIMITED)
        val sourceJob = launch(Dispatchers.Default) { source.start(channel) }
        try {
            val firstTwo =
                withTimeout(Duration.ofSeconds(5).toMillis()) {
                    List(2) {
                        val envelope = channel.receive()
                        @Suppress("UNCHECKED_CAST")
                        val row = envelope.event.payload?.getOrNull() as Map<String, Any?>
                        envelope.replyTo.complete(envelope.event)
                        (row.entries.first { it.key.equals("id", ignoreCase = true) }.value as Number).toLong()
                    }
                }
            assertEquals(listOf(1L, 2L), firstTwo)
            operations.executeDdl(
                DbExecuteDdlConfig(
                    ref(),
                    "INSERT INTO events(id, updated_at, body) VALUES (3, TIMESTAMP '2026-01-01 00:00:00', 'third')",
                ),
                MuseEvent(),
            )
            val third =
                withTimeout(Duration.ofSeconds(5).toMillis()) {
                    val envelope = channel.receive()
                    @Suppress("UNCHECKED_CAST")
                    val row = envelope.event.payload?.getOrNull() as Map<String, Any?>
                    envelope.replyTo.complete(envelope.event)
                    (row.entries.first { it.key.equals("id", ignoreCase = true) }.value as Number).toLong()
                }
            assertEquals(3L, third)
            assertNull(withTimeoutOrNull(250) { channel.receive() })
        } finally {
            source.stop()
            sourceJob.cancelAndJoin()
            channel.close()
        }
    }

    private fun ref(): DbConfigRef = DbConfigRef.ByReference(dbConfig)

    private object TestExpressionEvaluator : MuseExpressionEvaluator {
        override fun evaluate(expression: String, event: MuseEvent): TypedValue<Any>? =
            if (expression == "#[payload]") {
                event.payload
            } else {
                TypedValue.of(expression as Any)
            }
    }
}
