@TestInstance(TestInstance.Lifecycle.PER_CLASS)
@EnabledIfSystemProperty(named = "muse.db.postgres.it", matches = "true")
class DbPostgresFlowIT {
    private lateinit var postgres: PostgreSQLContainer

    @BeforeAll
    fun startPostgres() {
        postgres = PostgreSQLContainer("postgres:17-alpine")
        postgres.start()
    }

    @AfterAll
    fun stopPostgres() {
        if (::postgres.isInitialized) postgres.stop()
    }

    @Test
    fun `database DSL operations execute in a Muse flow against PostgreSQL`() = runBlocking {
        val db = databaseConfig()
        val flow =
            flow("postgres-db-operations") {
                dbExecuteDdl(db) {
                    sql = "DROP TABLE IF EXISTS muse_flow_account"
                    target = "dropResult"
                }
                dbExecuteDdl(db) {
                    sql =
                        "CREATE TABLE muse_flow_account (" +
                            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                            "name TEXT NOT NULL, balance INTEGER NOT NULL)"
                    target = "createResult"
                }
                dbInsert(db) {
                    sql = "INSERT INTO muse_flow_account(name, balance) VALUES (:name, :balance)"
                    inputParameters(mapOf("name" to "Ada", "balance" to 10))
                    generatedKeyColumn("id")
                    target = "insertResult"
                }
                dbQuerySingle(db) {
                    sql = "SELECT id FROM muse_flow_account WHERE id = :id"
                    inputParameters(mapOf("id" to "#[vars.insertResult.generatedKeys.id]"))
                    target = "selectedByGeneratedId"
                }
                dbUpdate(db) {
                    sql = "UPDATE muse_flow_account SET balance = :balance WHERE id = :id"
                    inputParameters(
                        mapOf(
                            "balance" to 15,
                            "id" to "#[vars.insertResult.generatedKeys.id]",
                        ),
                    )
                    target = "updateResult"
                }
                dbBulkInsert(db) {
                    sql = "INSERT INTO muse_flow_account(id, name, balance) VALUES (:id, :name, :balance)"
                    batchParameters(
                        listOf(
                            mapOf("id" to 100, "name" to "bulk-one", "balance" to 1),
                            mapOf("id" to 101, "name" to "bulk-two", "balance" to 2),
                        ),
                    )
                    target = "bulkInsertResult"
                }
                dbBulkUpdate(db) {
                    sql = "UPDATE muse_flow_account SET balance = :balance WHERE id = :id"
                    batchParameters(
                        listOf(
                            mapOf("id" to 100, "balance" to 20),
                            mapOf("id" to 101, "balance" to 30),
                        ),
                    )
                    target = "bulkUpdateResult"
                }
                dbDelete(db) {
                    sql = "DELETE FROM muse_flow_account WHERE id = :id"
                    inputParameters(mapOf("id" to "#[vars.insertResult.generatedKeys.id]"))
                    target = "deleteResult"
                }
                dbSelect(db) {
                    sql = "SELECT id, name, balance FROM muse_flow_account ORDER BY id"
                    streamingStrategy = StreamingStrategy.NonRepeatable
                    target = "rowsResult"
                }
            }.asStartedFlow()

        val originalAttributes = mapOf("request" to "preserve me")
        val input =
            MuseEvent(
                payload = TypedValue.of("original payload"),
                attributes = TypedValue.of(originalAttributes),
            )

        executeFlow(db, flow, input) { result ->
            assertNull(result.error)
            assertEquals("original payload", result.payload?.value)
            assertEquals(originalAttributes, result.attributes?.value)

            val insertResult = assertIs<DbStatementResult>(result.variables["insertResult"]?.value)
            assertEquals(1, insertResult.affectedRows)
            val generatedId = assertIs<Number>(insertResult.generatedKeys["id"]).toLong()
            assertEquals(1L, generatedId)

            val selected = assertIs<Map<*, *>>(result.variables["selectedByGeneratedId"]?.value)
            assertEquals(generatedId, (selected["id"] as Number).toLong())

            val updateResult = assertIs<DbStatementResult>(result.variables["updateResult"]?.value)
            assertEquals(1, updateResult.affectedRows)
            assertEquals(listOf(1, 1), result.variables["bulkInsertResult"]?.value)
            assertEquals(listOf(1, 1), result.variables["bulkUpdateResult"]?.value)
            assertEquals(1, result.variables["deleteResult"]?.value)

            val rowsProvider = assertIs<MuseCursorIteratorProvider<Map<String, Any?>>>(result.variables["rowsResult"]?.value)
            val rows = rowsProvider.openCursor().use { cursor -> cursor.asSequence().toList() }
            assertEquals(
                listOf(
                    mapOf("id" to 100L, "name" to "bulk-one", "balance" to 20),
                    mapOf("id" to 101L, "name" to "bulk-two", "balance" to 30),
                ),
                rows,
            )
        }
    }

    @Test
    fun `PostgreSQL backslash string literal leaves following named parameter bindable`() = runBlocking {
        val db = databaseConfig()
        val flow =
            flow("postgres-backslash-named-parameter") {
                dbQuerySingle(db) {
                    sql = """SELECT 'tail\' AS literal, :n AS n"""
                    inputParameters(mapOf("n" to 7))
                }
            }.asStartedFlow()

        executeFlow(db, flow, MuseEvent()) { result ->
            assertNull(result.error)
            val row = assertIs<Map<*, *>>(result.payload?.value)
            assertEquals("tail\\", row["literal"])
            assertEquals(7, (row["n"] as Number).toInt())
        }
    }

    private suspend fun executeFlow(
        db: DbConfig,
        flow: MuseFlow.Flow,
        event: MuseEvent,
        verify: (MuseEvent) -> Unit,
    ) {
        val factory = MuseComponentFactory()
        ServiceLoader.load(MuseComponentRegistrar::class.java).forEach { registrar -> registrar.register(factory) }
        factory.registerSource(PostgresTestSourceConfig::class) { component, _, _ -> NoOpMuseSource(component) }

        val application =
            bootstrap(
                MuseApplicationConfig(
                    flows = listOf(flow),
                    configs = listOf(db),
                    factory = factory,
                ),
            )
        val replyResources = StreamingResourceRegistry()
        try {
            application.init()
            application.start()
            val envelope = MuseEventEnvelope(event = event, replyResources = replyResources)
            application.channelFor(flow.name).send(envelope)
            verify(withTimeout(20_000) { envelope.replyTo.await() })
        } finally {
            replyResources.releaseAll()
            application.stop()
        }
    }

    private fun databaseConfig(): DbConfig =
        DbConfig(
            name = "postgres",
            connection =
                GenericDbConnectionConfig(
                    url = postgres.jdbcUrl,
                    driverClassName = "org.postgresql.Driver",
                    user = postgres.username,
                    password = postgres.password,
                ),
        )

    private fun MuseFlow.Flow.asStartedFlow(): MuseFlow.Flow =
        copy(
            source = PostgresTestSourceConfig(),
            initialState = FlowInitialState.STARTED,
        )
}

private data class PostgresTestSourceConfig(
    override val docName: String = "PostgreSQL flow test source",
    override val docId: String = "postgres-flow-test-source",
    override val docDescription: String? = null,
    override val sourceFile: String? = null,
    override val sourceLine: Int? = null,
    override val sourceClass: String? = null,
) : Source

private class NoOpMuseSource(
    config: PostgresTestSourceConfig,
) : MuseSource {
    override val docName: String = config.docName
    override val docId: String = config.docId
    override val docDescription: String? = config.docDescription
    override val sourceFile: String? = config.sourceFile
    override val sourceLine: Int? = config.sourceLine
    override val sourceClass: String? = config.sourceClass

    override suspend fun start(channel: SendChannel<MuseEventEnvelope>) = Unit

    override suspend fun stop() = Unit

    override suspend fun onResult(event: MuseEvent, transactionContext: Any?) = Unit
}
