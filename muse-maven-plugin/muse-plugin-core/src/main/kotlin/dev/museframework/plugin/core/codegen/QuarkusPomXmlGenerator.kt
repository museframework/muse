package dev.museframework.plugin.core.codegen

object QuarkusPomXmlGenerator {
    private const val QUARKUS_VERSION = "3.21.0"
    private const val KOTLIN_VERSION = "2.3.20"
    private const val MUSE_VERSION = "0.1.0"

    fun generate(config: MigrationProjectConfig): String {
        val hasHttp = "http" in config.namespaces

        return buildString {
            appendLine("<?xml version=\"1.0\" encoding=\"UTF-8\"?>")
            appendLine("<project xmlns=\"http://maven.apache.org/POM/4.0.0\"")
            appendLine("         xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\"")
            appendLine("         xsi:schemaLocation=\"http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd\">")
            appendLine("    <modelVersion>4.0.0</modelVersion>")
            appendLine()
            appendLine("    <groupId>${config.groupId.escapeXml()}</groupId>")
            appendLine("    <artifactId>${config.artifactId.escapeXml()}</artifactId>")
            appendLine("    <version>${config.version.escapeXml()}</version>")
            appendLine()
            appendLine("    <properties>")
            appendLine("        <java.version>21</java.version>")
            appendLine("        <kotlin.version>$KOTLIN_VERSION</kotlin.version>")
            appendLine("        <muse.version>$MUSE_VERSION</muse.version>")
            appendLine("        <quarkus.version>$QUARKUS_VERSION</quarkus.version>")
            appendLine("        <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>")
            appendLine("        <maven.compiler.release>\${java.version}</maven.compiler.release>")
            appendLine("    </properties>")
            appendLine()
            appendLine("    <dependencyManagement>")
            appendLine("        <dependencies>")
            appendLine("            <dependency>")
            appendLine("                <groupId>io.quarkus</groupId>")
            appendLine("                <artifactId>quarkus-bom</artifactId>")
            appendLine("                <version>\${quarkus.version}</version>")
            appendLine("                <type>pom</type>")
            appendLine("                <scope>import</scope>")
            appendLine("            </dependency>")
            appendLine("            <dependency>")
            appendLine("                <groupId>dev.museframework</groupId>")
            appendLine("                <artifactId>muse-bom</artifactId>")
            appendLine("                <version>\${muse.version}</version>")
            appendLine("                <type>pom</type>")
            appendLine("                <scope>import</scope>")
            appendLine("            </dependency>")
            appendLine("        </dependencies>")
            appendLine("    </dependencyManagement>")
            appendLine()
            appendLine("    <dependencies>")
            appendLine("        <dependency>")
            appendLine("            <groupId>io.quarkus</groupId>")
            appendLine("            <artifactId>quarkus-arc</artifactId>")
            appendLine("        </dependency>")
            appendLine("        <dependency>")
            appendLine("            <groupId>io.quarkus</groupId>")
            appendLine("            <artifactId>quarkus-kotlin</artifactId>")
            appendLine("        </dependency>")
            appendLine("        <dependency>")
            appendLine("            <groupId>io.quarkus</groupId>")
            appendLine("            <artifactId>quarkus-vertx-http</artifactId>")
            appendLine("        </dependency>")
            appendLine("        <dependency>")
            appendLine("            <groupId>io.quarkus</groupId>")
            appendLine("            <artifactId>quarkus-container-image-jib</artifactId>")
            appendLine("        </dependency>")
            appendLine()
            appendLine("        <dependency>")
            appendLine("            <groupId>dev.museframework.connectors</groupId>")
            appendLine("            <artifactId>muse-quarkus</artifactId>")
            appendLine("            <version>\${muse.version}</version>")
            appendLine("        </dependency>")
            if (hasHttp) {
                appendLine("        <dependency>")
                appendLine("            <groupId>dev.museframework.connectors</groupId>")
                appendLine("            <artifactId>muse-http-connector-quarkus</artifactId>")
                appendLine("            <version>\${muse.version}</version>")
                appendLine("        </dependency>")
            }
            appendLine("    </dependencies>")
            appendLine()
            appendLine("    <build>")
            appendLine("        <sourceDirectory>\${project.basedir}/src/main/kotlin</sourceDirectory>")
            appendLine("        <testSourceDirectory>\${project.basedir}/src/test/kotlin</testSourceDirectory>")
            appendLine("        <plugins>")
            appendLine("            <plugin>")
            appendLine("                <groupId>io.quarkus</groupId>")
            appendLine("                <artifactId>quarkus-maven-plugin</artifactId>")
            appendLine("                <version>\${quarkus.version}</version>")
            appendLine("                <extensions>true</extensions>")
            appendLine("                <executions>")
            appendLine("                    <execution>")
            appendLine("                        <goals>")
            appendLine("                            <goal>build</goal>")
            appendLine("                            <goal>generate-code</goal>")
            appendLine("                            <goal>generate-code-tests</goal>")
            appendLine("                        </goals>")
            appendLine("                    </execution>")
            appendLine("                </executions>")
            appendLine("            </plugin>")
            appendLine("            <plugin>")
            appendLine("                <groupId>org.jetbrains.kotlin</groupId>")
            appendLine("                <artifactId>kotlin-maven-plugin</artifactId>")
            appendLine("                <version>\${kotlin.version}</version>")
            appendLine("                <configuration>")
            appendLine("                    <jvmTarget>\${java.version}</jvmTarget>")
            appendLine("                    <javaParameters>true</javaParameters>")
            appendLine("                    <compilerPlugins>")
            appendLine("                        <plugin>all-open</plugin>")
            appendLine("                    </compilerPlugins>")
            appendLine("                    <pluginOptions>")
            appendLine("                        <option>all-open:annotation=jakarta.enterprise.context.ApplicationScoped</option>")
            appendLine("                    </pluginOptions>")
            appendLine("                </configuration>")
            appendLine("                <dependencies>")
            appendLine("                    <dependency>")
            appendLine("                        <groupId>org.jetbrains.kotlin</groupId>")
            appendLine("                        <artifactId>kotlin-maven-allopen</artifactId>")
            appendLine("                        <version>\${kotlin.version}</version>")
            appendLine("                    </dependency>")
            appendLine("                </dependencies>")
            appendLine("                <executions>")
            appendLine("                    <execution>")
            appendLine("                        <id>compile</id>")
            appendLine("                        <goals><goal>compile</goal></goals>")
            appendLine("                    </execution>")
            appendLine("                    <execution>")
            appendLine("                        <id>test-compile</id>")
            appendLine("                        <goals><goal>test-compile</goal></goals>")
            appendLine("                    </execution>")
            appendLine("                </executions>")
            appendLine("            </plugin>")
            appendLine("        </plugins>")
            appendLine("    </build>")
            if (config.nativeBuild) {
                appendLine()
                appendLine("    <profiles>")
                appendLine("        <profile>")
                appendLine("            <id>native</id>")
                appendLine("            <properties>")
                appendLine("                <quarkus.native.enabled>true</quarkus.native.enabled>")
                appendLine("                <skipITs>false</skipITs>")
                appendLine("            </properties>")
                appendLine("        </profile>")
                appendLine("    </profiles>")
            }
            appendLine("</project>")
        }
    }
}
