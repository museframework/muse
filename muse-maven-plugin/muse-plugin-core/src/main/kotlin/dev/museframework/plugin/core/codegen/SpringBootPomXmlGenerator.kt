package dev.museframework.plugin.core.codegen

object SpringBootPomXmlGenerator {

    fun generate(config: MigrationProjectConfig): String {
        val hasHttp = "http" in config.namespaces
        val hasApikit = "apikit" in config.namespaces

        return buildString {
            appendLine("<?xml version=\"1.0\" encoding=\"UTF-8\"?>")
            appendLine("<project xmlns:xsi=\"http://www.w3.org/2001/XMLSchema-instance\"")
            appendLine("         xmlns=\"http://maven.apache.org/POM/4.0.0\"")
            appendLine("         xsi:schemaLocation=\"http://maven.apache.org/POM/4.0.0 http://maven.apache.org/xsd/maven-4.0.0.xsd\">")
            appendLine("    <modelVersion>4.0.0</modelVersion>")
            appendLine()
            appendLine("    <parent>")
            appendLine("        <groupId>org.springframework.boot</groupId>")
            appendLine("        <artifactId>spring-boot-starter-parent</artifactId>")
            appendLine("        <version>4.0.3</version>")
            appendLine("        <relativePath/>")
            appendLine("    </parent>")
            appendLine()
            appendLine("    <dependencyManagement>")
            appendLine("        <dependencies>")
            appendLine("            <dependency>")
            appendLine("                <groupId>dev.museframework</groupId>")
            appendLine("                <artifactId>muse-bom</artifactId>")
            appendLine("                <version>0.1.0</version>")
            appendLine("                <type>pom</type>")
            appendLine("                <scope>import</scope>")
            appendLine("            </dependency>")
            appendLine("        </dependencies>")
            appendLine("    </dependencyManagement>")
            appendLine()
            appendLine("    <groupId>${config.groupId.escapeXml()}</groupId>")
            appendLine("    <artifactId>${config.artifactId.escapeXml()}</artifactId>")
            appendLine("    <version>${config.version.escapeXml()}</version>")
            appendLine()
            appendLine("    <properties>")
            appendLine("        <java.version>21</java.version>")
            appendLine("        <kotlin.version>2.3.20</kotlin.version>")
            appendLine("        <project.build.sourceEncoding>UTF-8</project.build.sourceEncoding>")
            appendLine("        <project.reporting.outputEncoding>UTF-8</project.reporting.outputEncoding>")
            appendLine("        <maven.compiler.source>\${java.version}</maven.compiler.source>")
            appendLine("        <maven.compiler.target>\${java.version}</maven.compiler.target>")
            appendLine("    </properties>")
            appendLine()
            appendLine("    <dependencies>")
            appendLine("        <dependency>")
            appendLine("            <groupId>org.springframework.boot</groupId>")
            appendLine("            <artifactId>spring-boot-starter</artifactId>")
            appendLine("        </dependency>")
            appendLine("        <dependency>")
            appendLine("            <groupId>org.springframework.boot</groupId>")
            appendLine("            <artifactId>spring-boot-starter-web</artifactId>")
            appendLine("        </dependency>")
            appendLine("        <dependency>")
            appendLine("            <groupId>org.jetbrains.kotlin</groupId>")
            appendLine("            <artifactId>kotlin-reflect</artifactId>")
            appendLine("        </dependency>")
            appendLine("        <dependency>")
            appendLine("            <groupId>org.jetbrains.kotlin</groupId>")
            appendLine("            <artifactId>kotlin-stdlib</artifactId>")
            appendLine("        </dependency>")
            appendLine()
            appendLine("        <dependency>")
            appendLine("            <groupId>dev.museframework.connectors</groupId>")
            appendLine("            <artifactId>muse-spring-boot</artifactId>")
            appendLine("            <version>0.1.0</version>")
            appendLine("        </dependency>")
            if (hasHttp) {
                appendLine("        <dependency>")
                appendLine("            <groupId>dev.museframework.connectors</groupId>")
                appendLine("            <artifactId>muse-http-connector-spring</artifactId>")
                appendLine("            <version>0.1.0</version>")
                appendLine("        </dependency>")
            }
            if (hasApikit) {
                appendLine("        <dependency>")
                appendLine("            <groupId>dev.museframework.connectors</groupId>")
                appendLine("            <artifactId>muse-apikit-connector-spring</artifactId>")
                appendLine("            <version>0.1.0</version>")
                appendLine("        </dependency>")
            }
            appendLine()
            appendLine("        <dependency>")
            appendLine("            <groupId>org.springframework.boot</groupId>")
            appendLine("            <artifactId>spring-boot-starter-test</artifactId>")
            appendLine("            <scope>test</scope>")
            appendLine("        </dependency>")
            appendLine("        <dependency>")
            appendLine("            <groupId>org.jetbrains.kotlin</groupId>")
            appendLine("            <artifactId>kotlin-test-junit5</artifactId>")
            appendLine("            <scope>test</scope>")
            appendLine("        </dependency>")
            appendLine("    </dependencies>")
            appendLine()
            appendLine("    <build>")
            appendLine("        <sourceDirectory>\${project.basedir}/src/main/kotlin</sourceDirectory>")
            appendLine("        <testSourceDirectory>\${project.basedir}/src/test/kotlin</testSourceDirectory>")
            appendLine("        <plugins>")
            appendLine("            <plugin>")
            appendLine("                <groupId>org.jetbrains.kotlin</groupId>")
            appendLine("                <artifactId>kotlin-maven-plugin</artifactId>")
            appendLine("                <version>\${kotlin.version}</version>")
            appendLine("                <configuration>")
            appendLine("                    <args>")
            appendLine("                        <arg>-Xjsr305=strict</arg>")
            appendLine("                    </args>")
            appendLine("                    <compilerPlugins>")
            appendLine("                        <plugin>spring</plugin>")
            appendLine("                    </compilerPlugins>")
            appendLine("                </configuration>")
            appendLine("                <dependencies>")
            appendLine("                    <dependency>")
            appendLine("                        <groupId>org.jetbrains.kotlin</groupId>")
            appendLine("                        <artifactId>kotlin-maven-allopen</artifactId>")
            appendLine("                        <version>\${kotlin.version}</version>")
            appendLine("                    </dependency>")
            appendLine("                </dependencies>")
            appendLine("                <executions>")
            appendLine("                    <execution>")
            appendLine("                        <id>compile</id>")
            appendLine("                        <phase>process-sources</phase>")
            appendLine("                        <goals><goal>compile</goal></goals>")
            appendLine("                    </execution>")
            appendLine("                    <execution>")
            appendLine("                        <id>test-compile</id>")
            appendLine("                        <phase>process-test-sources</phase>")
            appendLine("                        <goals><goal>test-compile</goal></goals>")
            appendLine("                    </execution>")
            appendLine("                </executions>")
            appendLine("            </plugin>")
            appendLine("            <plugin>")
            appendLine("                <groupId>org.springframework.boot</groupId>")
            appendLine("                <artifactId>spring-boot-maven-plugin</artifactId>")
            appendLine("                <executions>")
            appendLine("                    <execution>")
            appendLine("                        <goals><goal>build-info</goal></goals>")
            appendLine("                    </execution>")
            appendLine("                </executions>")
            appendLine("            </plugin>")
            if (config.nativeBuild) {
                appendLine("            <plugin>")
                appendLine("                <groupId>org.graalvm.buildtools</groupId>")
                appendLine("                <artifactId>native-maven-plugin</artifactId>")
                appendLine("            </plugin>")
            }
            appendLine("        </plugins>")
            appendLine("    </build>")
            appendLine()
            appendLine("    <repositories>")
            appendLine("        <repository>")
            appendLine("            <id>mulesoft-releases</id>")
            appendLine("            <url>https://repository.mulesoft.org/releases/</url>")
            appendLine("        </repository>")
            appendLine("    </repositories>")
            appendLine()
            if (config.nativeBuild) {
                appendLine("    <profiles>")
                appendLine("        <profile>")
                appendLine("            <id>native</id>")
                appendLine("            <build>")
                appendLine("                <plugins>")
                appendLine("                    <plugin>")
                appendLine("                        <groupId>org.graalvm.buildtools</groupId>")
                appendLine("                        <artifactId>native-maven-plugin</artifactId>")
                appendLine("                        <configuration>")
                appendLine("                            <buildArgs>")
                appendLine("                                <buildArg>--no-fallback</buildArg>")
                appendLine("                                <buildArg>--enable-preview</buildArg>")
                appendLine("                                <buildArg>-H:+ReportExceptionStackTraces</buildArg>")
                appendLine("                            </buildArgs>")
                appendLine("                        </configuration>")
                appendLine("                        <executions>")
                appendLine("                            <execution>")
                appendLine("                                <id>build-native</id>")
                appendLine("                                <goals><goal>compile-no-fork</goal></goals>")
                appendLine("                                <phase>package</phase>")
                appendLine("                            </execution>")
                appendLine("                        </executions>")
                appendLine("                    </plugin>")
                appendLine("                </plugins>")
                appendLine("            </build>")
                appendLine("        </profile>")
                appendLine("    </profiles>")
                appendLine()
            }
            appendLine("</project>")
        }
    }
}
