package dev.museframework.plugin.core.runtime.spring

import dev.museframework.babelfish.emitter.ConfigurationClassSpec
import dev.museframework.plugin.core.codegen.GeneratedFile
import dev.museframework.plugin.core.codegen.MigrationProjectConfig
import dev.museframework.plugin.core.codegen.MuseAppConfig
import dev.museframework.plugin.core.codegen.SpringBootPomXmlGenerator
import dev.museframework.plugin.core.codegen.ValidationError
import dev.museframework.plugin.core.runtime.MuseRuntime
import dev.museframework.plugin.core.runtime.RunCommand
import dev.museframework.plugin.core.runtime.RuntimeStrategy

class SpringBootRuntimeStrategy : RuntimeStrategy {
    override val runtime = MuseRuntime.SpringBoot

    override fun validate(config: MuseAppConfig): List<ValidationError> {
        val errors = mutableListOf<ValidationError>()
        val hasMuseSpringBoot =
            config.artifacts.any {
                it.isRelevant() && it.artifactId == "muse-spring-boot"
            }
        if (!hasMuseSpringBoot) {
            errors +=
                ValidationError(
                    message =
                        "'dev.museframework.connectors:muse-spring-boot' was not found in " +
                            "compile/runtime dependencies. Generated Spring configuration classes " +
                            "require the Muse Spring Boot integration.",
                    fatal = true,
                )
        }
        errors += flowWarnings(config)
        return errors
    }

    override fun validateMigration(config: MuseAppConfig): List<ValidationError> = flowWarnings(config)

    override fun configurationClassSpec(): ConfigurationClassSpec =
        ConfigurationClassSpec(
            definition =
                ConfigurationClassSpec.Declaration(
                    annotationTypes = listOf("dev.museframework.springboot.MuseConfigComponent"),
                ),
            native =
                ConfigurationClassSpec.Declaration(
                    annotationTypes =
                        listOf(
                            "dev.museframework.dsl.annotation.MuseConfig",
                            "org.springframework.stereotype.Component",
                        ),
                    providerInterface = "dev.museframework.springboot.MuseConfigProvider",
                ),
        )

    override fun generateRuntimeFiles(config: MuseAppConfig): List<GeneratedFile> {
        val className = "${config.applicationName}Application"
        val entryPoint =
            GeneratedFile(
                relativePath = "${config.packageName.replace('.', '/')}/$className.kt",
                content =
                    """
                    package ${config.packageName}

                    import dev.museframework.springboot.MuseApplication
                    import dev.museframework.springboot.runMuseApplication
                    import org.springframework.boot.WebApplicationType
                    import org.springframework.context.annotation.ComponentScan

                    /**
                     * Application entry point generated by muse-maven-plugin.
                     * DO NOT EDIT — this file is regenerated on every build.
                     */
                    fun main(args: Array<String>) {
                        runMuseApplication<${className}Marker>(args)
                    }

                    @MuseApplication(webEnvironment = WebApplicationType.SERVLET)
                    @ComponentScan(basePackages = ["${config.packageName}", "dev.museframework"])
                    class ${className}Marker
                    """.trimIndent(),
            )
        val properties =
            GeneratedFile(
                relativePath = "resources/application-muse.properties",
                content =
                    """
                    # Generated by muse-maven-plugin — DO NOT EDIT
                    muse.application.name=${config.applicationName}
                    """.trimIndent(),
                kind = GeneratedFile.Kind.RESOURCE,
            )
        return listOf(entryPoint, properties)
    }

    override fun generatePom(config: MigrationProjectConfig): String =
        SpringBootPomXmlGenerator.generate(config)

    override fun runCommand(config: MuseAppConfig): RunCommand {
        val mainClassName = "${config.packageName}.${config.applicationName}ApplicationKt"
        return RunCommand.DelegateMavenPlugin(
            groupId = "org.springframework.boot",
            artifactId = "spring-boot-maven-plugin",
            goal = "run",
            configuration = mapOf("mainClass" to mainClassName, "addResources" to "true"),
        )
    }

    override fun buildCommand(config: MuseAppConfig): RunCommand =
        RunCommand.DelegateMavenPlugin(
            groupId = "org.springframework.boot",
            artifactId = "spring-boot-maven-plugin",
            goal = "repackage",
        )

    override fun dockerCommand(config: MuseAppConfig): RunCommand =
        RunCommand.DelegateMavenPlugin(
            groupId = "org.springframework.boot",
            artifactId = "spring-boot-maven-plugin",
            goal = "build-image",
        )

    private fun flowWarnings(config: MuseAppConfig): List<ValidationError> =
        if (config.flowConfigClassNames.isEmpty()) {
            listOf(
                ValidationError(
                    message =
                        "No Muse configuration classes were generated. Verify that the source " +
                            "directory contains valid MuleSoft XML files.",
                    fatal = false,
                ),
            )
        } else {
            emptyList()
        }
}
