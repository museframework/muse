package dev.museframework.plugin.core.runtime.quarkus

import dev.museframework.babelfish.emitter.ConfigurationClassSpec
import dev.museframework.plugin.core.codegen.GeneratedFile
import dev.museframework.plugin.core.codegen.MigrationProjectConfig
import dev.museframework.plugin.core.codegen.MuseAppConfig
import dev.museframework.plugin.core.codegen.QuarkusPomXmlGenerator
import dev.museframework.plugin.core.codegen.ValidationError
import dev.museframework.plugin.core.runtime.MuseRuntime
import dev.museframework.plugin.core.runtime.RunCommand
import dev.museframework.plugin.core.runtime.RuntimeStrategy

class QuarkusRuntimeStrategy : RuntimeStrategy {
    override val runtime = MuseRuntime.Quarkus

    override fun validate(config: MuseAppConfig): List<ValidationError> {
        val errors = mutableListOf<ValidationError>()
        val hasMuseQuarkus =
            config.artifacts.any {
                it.isRelevant() && it.artifactId == "muse-quarkus"
            }
        if (!hasMuseQuarkus) {
            errors +=
                ValidationError(
                    message =
                        "'dev.museframework.connectors:muse-quarkus' was not found in " +
                            "compile/runtime dependencies. Generated Quarkus configuration classes " +
                            "require the Muse Quarkus extension.",
                    fatal = true,
                )
        }
        errors += migrationCompatibilityErrors(config)
        errors += flowWarnings(config)
        return errors
    }

    override fun validateMigration(config: MuseAppConfig): List<ValidationError> =
        migrationCompatibilityErrors(config) + flowWarnings(config)

    override fun configurationClassSpec(): ConfigurationClassSpec =
        ConfigurationClassSpec(
            definition =
                ConfigurationClassSpec.Declaration(
                    annotationTypes =
                        listOf(
                            "dev.museframework.dsl.annotation.MuseConfig",
                            "jakarta.enterprise.context.ApplicationScoped",
                        ),
                ),
            native =
                ConfigurationClassSpec.Declaration(
                    annotationTypes =
                        listOf(
                            "dev.museframework.dsl.annotation.MuseConfig",
                            "jakarta.enterprise.context.ApplicationScoped",
                        ),
                    providerInterface = "dev.museframework.quarkus.MuseConfigProvider",
                ),
        )

    override fun generateRuntimeFiles(config: MuseAppConfig): List<GeneratedFile> =
        listOf(
            GeneratedFile(
                relativePath = "resources/application.properties",
                content =
                    """
                    # Generated by muse-maven-plugin — DO NOT EDIT
                    quarkus.application.name=${config.applicationName}
                    """.trimIndent(),
                kind = GeneratedFile.Kind.RESOURCE,
            ),
        )

    override fun generatePom(config: MigrationProjectConfig): String =
        QuarkusPomXmlGenerator.generate(config)

    override fun runCommand(config: MuseAppConfig): RunCommand =
        RunCommand.DelegateMavenPlugin(
            groupId = "io.quarkus",
            artifactId = "quarkus-maven-plugin",
            goal = "dev",
        )

    override fun buildCommand(config: MuseAppConfig): RunCommand =
        RunCommand.DelegateMavenPlugin(
            groupId = "io.quarkus",
            artifactId = "quarkus-maven-plugin",
            goal = "build",
        )

    override fun dockerCommand(config: MuseAppConfig): RunCommand =
        RunCommand.DelegateMavenPlugin(
            groupId = "io.quarkus",
            artifactId = "quarkus-maven-plugin",
            goal = "image-build",
        )

    private fun migrationCompatibilityErrors(config: MuseAppConfig): List<ValidationError> =
        if ("apikit" in config.namespaces) {
            listOf(
                ValidationError(
                    message =
                        "APIKit migration is not supported for the Quarkus runtime because " +
                            "a Muse APIKit Quarkus adapter is not available.",
                    fatal = true,
                ),
            )
        } else {
            emptyList()
        }

    private fun flowWarnings(config: MuseAppConfig): List<ValidationError> =
        if (config.flowConfigClassNames.isEmpty()) {
            listOf(
                ValidationError(
                    message =
                        "No Muse configuration classes were generated. Verify that the source " +
                            "directory contains valid MuleSoft XML files.",
                    fatal = false,
                ),
            )
        } else {
            emptyList()
        }
}
